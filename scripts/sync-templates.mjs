// Generates each template directory from `builder/`.
//
// Layout:
//   builder/shared/   -> copied into every template
//   builder/<name>/   -> template-specific files (override shared on conflict)
//
// Output: a top-level `<name>/` directory per template, fully self-contained
// so `npm create astro@latest -- --template m1m0zzz/astro-template/<name>`
// (giget extracts only that subdirectory) works without symlinks.
//
// Run: `npm run sync`               one-shot (forward sync)
//      `npm run sync -- --watch`    rebuild on changes under builder/
//      `node scripts/sync-templates.mjs --reverse`
//                                   copy formatted output back into builder/
//
// Idempotent: each template dir is cleaned (except the generated/ignored dirs
// below) and rebuilt from scratch.

import {
  copyFileSync,
  cpSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  rmSync,
  symlinkSync,
  watch,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const builderDir = join(root, 'builder');
const sharedDir = join(builderDir, 'shared');

// Generated / dependency dirs that must survive a clean (regenerated by
// npm install / astro, expensive to delete, and git-ignored anyway).
const PRESERVE = new Set(['node_modules', '.astro', 'dist']);

// Files created as symlinks inside each template instead of real copies.
// Format: [target, linkName] -> `linkName` points to `target` (same directory).
const SYMLINKS = [['AGENTS.md', 'CLAUDE.md']];

function getTemplates() {
  const templates = readdirSync(builderDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name !== 'shared')
    .map((e) => e.name);

  if (templates.length === 0) {
    console.error('No templates found under builder/.');
    process.exit(1);
  }
  return templates;
}

function cleanTemplateDir(outDir) {
  if (!existsSync(outDir)) return;
  for (const entry of readdirSync(outDir)) {
    if (PRESERVE.has(entry)) continue;
    rmSync(join(outDir, entry), { recursive: true, force: true });
  }
}

// Relative paths of every real file under `dir`, skipping PRESERVE dirs.
function listFiles(dir, prefix = '') {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (PRESERVE.has(entry.name)) continue;
    const rel = join(prefix, entry.name);
    if (entry.isDirectory()) {
      out.push(...listFiles(join(dir, entry.name), rel));
    } else {
      out.push(rel);
    }
  }
  return out;
}

function copyBack(from, to) {
  if (!existsSync(from)) return;
  if (lstatSync(from).isSymbolicLink()) return; // don't follow generated symlinks
  copyFileSync(from, to);
  console.log(`synced back: ${relative(root, to)}`);
}

// Copy the formatted output back into builder/ so the source mirrors the
// committed result. Template-specific files map 1:1; a shared file is copied
// from a template that does not override it.
function syncBack() {
  const templates = getTemplates();

  for (const name of templates) {
    const outDir = join(root, name);
    for (const rel of listFiles(join(builderDir, name))) {
      copyBack(join(outDir, rel), join(builderDir, name, rel));
    }
  }

  for (const rel of listFiles(sharedDir)) {
    for (const name of templates) {
      if (existsSync(join(builderDir, name, rel))) continue; // overridden
      copyBack(join(root, name, rel), join(sharedDir, rel));
      break;
    }
  }
}

function sync() {
  const templates = getTemplates();

  for (const name of templates) {
    const outDir = join(root, name);
    cleanTemplateDir(outDir);
    mkdirSync(outDir, { recursive: true });

    // shared first, then template-specific so the template wins on conflicts.
    if (existsSync(sharedDir)) {
      cpSync(sharedDir, outDir, { recursive: true });
    }
    cpSync(join(builderDir, name), outDir, { recursive: true });

    // Replace configured files with symlinks (target is relative to the link).
    for (const [target, linkName] of SYMLINKS) {
      const linkPath = join(outDir, linkName);
      rmSync(linkPath, { force: true });
      symlinkSync(target, linkPath);
    }

    console.log(`synced: ${name}/`);
  }
}

if (process.argv.includes('--reverse')) {
  syncBack();
  process.exit(0);
}

sync();

if (process.argv.includes('--watch')) {
  console.log(`watching ${builderDir} for changes...`);
  let timer = null;
  // Debounce: editors emit bursts of events for a single save.
  watch(builderDir, { recursive: true }, (_event, filename) => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(() => {
      console.log(`change: ${filename ?? '(unknown)'} -> resyncing`);
      try {
        sync();
      } catch (err) {
        console.error(err);
      }
    }, 100);
  });
}
